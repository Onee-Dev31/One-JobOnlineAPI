-- sp_RefreshUniversitiesFromRaw: rebuilds Universities from UniversitiesRaw + UniversityOverride.
-- All rows in UniversitiesRaw are included (no exclusion filter) - military/police academies
-- and other "สถานศึกษานอกสังกัดฯ" institutions are kept and classified as 'public'.
-- Run this after re-importing a newer academic year into UniversitiesRaw, or after editing
-- UniversityOverride. English names are best-effort carried over by matching the resulting
-- Thai name against what was already in Universities (or NameEngOverride when no match exists).
CREATE OR ALTER PROCEDURE sp_RefreshUniversitiesFromRaw
AS
BEGIN
    SET NOCOUNT ON;

    SELECT UniversityNameThai, UniversityNameEng
    INTO #OldUniversityNames
    FROM Universities
    WHERE UniversityNameEng IS NOT NULL;

    TRUNCATE TABLE Universities;

    ;WITH Resolved AS (
        SELECT
            COALESCE(o.NameThaiOverride, r.UnivName) AS NameThai,
            o.NameEngOverride,
            COALESCE(o.TypeOverride,
                CASE
                    WHEN r.UnivTypeName IN (N'มหาวิทยาลัยในกำกับรัฐ', N'มหาวิทยาลัยของรัฐ', N'มหาวิทยาลัยราชภัฎ',
                                             N'มหาวิทยาลัยเทคโนโลยีราชมงคล', N'มหาวิทยาลัยรัฐไม่จำกัดรับ',
                                             N'สถานศึกษานอกสังกัดฯ') THEN 'public'
                    WHEN r.UnivTypeName IN (N'มหาวิทยาลัยเอกชน', N'สถาบันเอกชน', N'วิทยาลัยเอกชน') THEN 'private'
                END) AS UnivType
        FROM UniversitiesRaw r
        LEFT JOIN UniversityOverride o ON o.UnivID = r.UnivID
    )
    INSERT INTO Universities (UniversityNameThai, UniversityNameEng, UniversityType)
    SELECT
        res.NameThai,
        COALESCE(res.NameEngOverride, old.UniversityNameEng),
        res.UnivType
    FROM Resolved res
    LEFT JOIN #OldUniversityNames old ON old.UniversityNameThai = res.NameThai;

    DROP TABLE #OldUniversityNames;

    DECLARE @Total INT = (SELECT COUNT(*) FROM Universities);
    DECLARE @MissingEng INT = (SELECT COUNT(*) FROM Universities WHERE UniversityNameEng IS NULL);
    PRINT 'Refreshed Universities: ' + CAST(@Total AS NVARCHAR(10)) + ' rows, ' + CAST(@MissingEng AS NVARCHAR(10)) + ' missing English name';
END
GO

EXEC sp_RefreshUniversitiesFromRaw;
